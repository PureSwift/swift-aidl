public struct AIDLSwiftGenerationError: Error, Sendable, CustomStringConvertible {
    public let sourcePath: String
    public let message: String

    public var description: String { "\(sourcePath): \(message)" }
}

/// Emits Swift bindings for the root declaration.
struct AIDLSwiftGenerator {
    let file: AIDLFile
    let resolver: AIDLTypeResolver
    let integerConstants: [String: Int64]
    let interfaceVersion: Int32?
    let interfaceHash: String?
    let manualParcelables: Set<String>

    private static let header = ["// Generated by aidl-swift.", "import Binder", ""]

    func generate() throws -> String {
        guard file.declarations.count == 1, let declaration = file.declarations.first else {
            throw failure("Swift generation requires one declaration in the root file")
        }
        if interfaceVersion != nil || interfaceHash != nil {
            guard case .interface = declaration else {
                throw failure("version and hash options require an interface")
            }
        }
        let lines: [String]
        switch declaration {
        case let .interface(interface):
            lines = try generateInterface(interface)
        case let .parcelable(parcelable):
            lines = try generateParcelable(parcelable)
        case let .enumeration(enumeration):
            lines = try generateEnum(enumeration)
        case let .union(union):
            lines = try generateUnion(union)
        }
        return (Self.header + lines + [""]).joined(separator: "\n")
    }

    private func generateInterface(_ interface: AIDLInterface) throws -> [String] {
        guard interface.annotations.isEmpty, interface.nestedDeclarations.isEmpty else {
            throw failure("Swift generation does not support interface annotations or nested declarations")
        }
        let name = try identifier(interface.name)
        var methods = try interface.methods.map { try makeMethod($0, interfaceIsOneway: interface.isOneway) }
        guard Set(methods.map(\.name)).count == methods.count else {
            throw failure("Swift generation does not support overloaded methods")
        }
        guard Set(methods.map(\.code)).count == methods.count else {
            throw failure("duplicate transaction code")
        }
        let explicitCount = interface.methods.filter { $0.explicitTransactionId != nil }.count
        guard explicitCount == 0 || explicitCount == methods.count else {
            throw failure("transaction IDs must be specified for all methods or none")
        }
        for method in try metadataMethods() {
            guard !methods.contains(where: { $0.name == method.name }) else {
                throw failure("method '\(method.name)' conflicts with generated Stable AIDL metadata")
            }
            methods.append(method)
        }
        let constants = try generateInterfaceConstants(interface, methodNames: Set(methods.map(\.name)))
        let methodTypes = methods.flatMap { $0.parameters + ($0.result.map { [$0] } ?? []) }
        try validateSwiftTypeNames(methodTypes)

        var lines = ["public protocol \(escaped(name)): BinderInterface {"]
        lines += methods.map { "    \($0.signature)" }
        lines += [
            "}",
            "",
            "public extension \(escaped(name)) {",
            "    static var descriptor: String { \(String(reflecting: interface.descriptor)) }",
        ]
        lines += constants
        lines += [
            "}",
            "",
            "public enum \(name)TransactionCode {",
        ]
        lines += methods.map { "    public static let \(escaped($0.name)): UInt32 = \($0.code)" }
        lines += [
            "}",
            "",
            "public struct \(name)Proxy: \(escaped(name)), BinderProxy {",
            "    public let remote: any IBinder",
            "",
            "    public init(remote: any IBinder) {",
            "        self.remote = remote",
            "    }",
            "",
            "    public init(remote: RemoteProxy) {",
            "        self.init(remote: RemoteEndpoint(proxy: remote))",
            "    }",
            "",
            "    private final class RemoteEndpoint: IBinder {",
            "        let proxy: RemoteProxy",
            "",
            "        init(proxy: RemoteProxy) {",
            "            self.proxy = proxy",
            "        }",
            "",
            "        func transact(code: UInt32, data: Parcel, flags: TransactionFlags) async throws -> Parcel {",
            "            try await proxy.transact(code: code, request: data, flags: flags)",
            "        }",
            "    }",
        ]
        for method in methods {
            lines += proxy(method, interfaceName: name)
        }
        lines += [
            "}",
            "",
            "open class \(name)Stub: BinderStub, \(escaped(name)), @unchecked Sendable {",
            "    public init() {",
            "        super.init(descriptor: Self.descriptor)",
            "    }",
            "",
            "    public final func asBinder() -> any IBinder { self }",
        ]
        for method in methods {
            let implementation = method.stubValue.map { "return " + $0 }
                ?? "throw BinderTransactionError.unknownTransaction(\(name)TransactionCode.\(escaped(method.name)))"
            lines += [
                "",
                "    open \(method.signature) {",
                "        \(implementation)",
                "    }",
            ]
        }
        lines += [
            "",
            "    public override func onTransact(",
            "        code: UInt32, data: inout Parcel.Reader, reply: inout Parcel, flags: TransactionFlags",
            "    ) async throws -> Bool {",
            "        switch code {",
        ]
        for method in methods {
            lines += dispatch(method, interfaceName: name)
        }
        lines += [
            "        default:",
            "            return try await super.onTransact(code: code, data: &data, reply: &reply, flags: flags)",
            "        }",
            "    }",
            "}",
        ]
        lines += arrayCodec(for: methodTypes, owner: name)
        if methodTypes.contains(where: \.usesManualParcelableCodec) {
            lines += manualParcelableCodec(owner: name)
        }
        return lines
    }

    private func manualParcelableCodec(owner: String) -> [String] {
        [
            "",
            "private enum \(owner)ManualParcelableCodec {",
            "    static func readRequired<Value: BinderParcelable>(",
            "        _ type: Value.Type, from reader: inout Parcel.Reader",
            "    ) throws -> Value {",
            "        guard let value = try read(type, from: &reader) else { throw BinderError.failedTransaction }",
            "        return value",
            "    }",
            "",
            "    static func read<Value: BinderParcelable>(",
            "        _ type: Value.Type, from reader: inout Parcel.Reader",
            "    ) throws -> Value? {",
            "        guard try reader.readInt32() != 0 else { return nil }",
            "        return try Value(from: &reader)",
            "    }",
            "",
            "    static func write<Value: BinderParcelable>(_ value: Value?, to parcel: inout Parcel) throws {",
            "        guard let value else {",
            "            parcel.append(Int32(0))",
            "            return",
            "        }",
            "        parcel.append(Int32(1))",
            "        try value.write(to: &parcel)",
            "    }",
            "}",
        ]
    }

    private func arrayCodec(for types: [WireType], owner: String) -> [String] {
        guard types.contains(where: \.usesArrayCodec) else { return [] }
        let requiresStringReader = types.contains {
            if case .stringCollection(_, nullable: false) = $0 { return true }
            return false
        }
        var lines = [
            "",
            "private enum \(owner)ArrayCodec {",
            "    static func read<Element>(",
            "        from reader: inout Parcel.Reader, elementSize: Int,",
            "        readElement: (inout Parcel.Reader) throws -> Element",
            "    ) throws -> [Element]? {",
            "        let count = try reader.readInt32()",
            "        if count == -1 { return nil }",
            "        guard count >= 0 else { throw ParcelError.invalidLength(count) }",
            "        guard Int(count) <= reader.remaining / elementSize else { throw ParcelError.endOfParcel }",
            "        return try (0..<Int(count)).map { _ in try readElement(&reader) }",
            "    }",
            "",
            "    static func write<Element>(",
            "        _ values: [Element]?, to parcel: inout Parcel,",
            "        writeElement: (Element, inout Parcel) throws -> Void",
            "    ) throws {",
            "        guard let values else {",
            "            parcel.append(Int32(-1))",
            "            return",
            "        }",
            "        guard let count = Int32(exactly: values.count) else { throw BinderError.failedTransaction }",
            "        parcel.append(count)",
            "        for value in values { try writeElement(value, &parcel) }",
            "    }",
        ]
        if requiresStringReader {
            lines += [
                "",
                "    static func readRequiredString(from reader: inout Parcel.Reader) throws -> String {",
                "        guard let value = try reader.readString() else { throw ParcelError.invalidLength(-1) }",
                "        return value",
                "    }",
            ]
        }
        return lines + ["}"]
    }

    private func generateInterfaceConstants(_ interface: AIDLInterface, methodNames: Set<String>) throws -> [String] {
        var names = methodNames
        let declarations = try interface.constants.map { constant in
            let qualifiedName = interface.descriptor + "." + constant.name
            let name = try identifier(constant.name)
            guard names.insert(name).inserted else {
                throw failure("conflicting Swift name for interface constant '\(qualifiedName)'")
            }
            return constant
        }
        let strings = Dictionary(uniqueKeysWithValues: declarations
            .filter { $0.type.name == "String" && isPlain($0.type) }
            .map { ($0.name, $0.value) })
        var evaluator = StringConstantEvaluator(definitions: strings, interfaceDescriptor: interface.descriptor)
        return try declarations.map { constant in
            let qualifiedName = interface.descriptor + "." + constant.name
            let name = escaped(constant.name)
            if strings[constant.name] != nil {
                let value = try evaluator.evaluate(constant.name)
                return "    static var \(name): String { \(String(reflecting: value)) }"
            }
            if isPlain(constant.type), let type = Scalar(rawValue: constant.type.name),
               let value = integerConstants[qualifiedName] {
                return "    static var \(name): \(type.swiftType) { \(value) }"
            }
            throw failure("unsupported Swift type '\(constant.type.name)' for interface constant '\(qualifiedName)'")
        }
    }

    private func metadataMethods() throws -> [Method] {
        var methods: [Method] = []
        if let interfaceVersion {
            guard interfaceVersion > 0 else { throw failure("interface version must be positive") }
            methods.append(Method(
                name: "getInterfaceVersion", code: 0x00ff_ffff, parameters: [],
                result: .scalar(.int), isOneway: false, stubValue: String(interfaceVersion)
            ))
        }
        if let interfaceHash {
            guard !interfaceHash.isEmpty else { throw failure("interface hash must not be empty") }
            methods.append(Method(
                name: "getInterfaceHash", code: 0x00ff_fffe, parameters: [],
                result: .reference(.string, nullable: false), isOneway: false, stubValue: String(reflecting: interfaceHash)
            ))
        }
        return methods
    }

    private func proxy(_ method: Method, interfaceName: String) -> [String] {
        var lines = [
            "",
            "    public \(method.signature) {",
            "        var request = Parcel()",
            "        request.appendInterfaceToken(Self.descriptor)",
        ]
        for (index, type) in method.parameters.enumerated() {
            lines.append("        \(type.write("argument\(index)", to: "request"))")
        }
        let code = "\(interfaceName)TransactionCode.\(escaped(method.name))"
        if method.isOneway {
            lines.append("        _ = try await remote.transact(code: \(code), data: request, flags: .oneWay)")
        } else {
            lines += [
                "        let reply = try await remote.transact(code: \(code), data: request, flags: [])",
                "        var reader = reply.reader()",
                "        try reader.readException()",
            ]
            if !method.inoutParameters.isEmpty {
                if let result = method.result {
                    lines.append("        \(result.decode(from: "reader", binding: "result"))")
                }
                for index in method.inoutParameters {
                    lines.append("        \(method.parameters[index].decode(from: "reader", binding: "updated\(index)"))")
                    lines.append("        guard updated\(index).count == argument\(index).count else { throw BinderError.failedTransaction }")
                }
                for index in method.inoutParameters {
                    lines.append("        argument\(index) = updated\(index)")
                }
                if method.result != nil { lines.append("        return result") }
            } else if let result = method.result {
                if result.requiresNonNullRead {
                    lines.append("        \(result.decode(from: "reader", binding: "result"))")
                    lines.append("        return result")
                } else {
                    lines.append("        return try \(result.read(from: "reader"))")
                }
            }
        }
        lines.append("    }")
        return lines
    }

    private func dispatch(_ method: Method, interfaceName: String) -> [String] {
        var lines = [
            "        case \(interfaceName)TransactionCode.\(escaped(method.name)):",
            "            try data.enforceInterface(Self.descriptor)",
        ]
        for (index, type) in method.parameters.enumerated() {
            let mutable = method.inoutParameters.contains(index)
            lines.append("            \(type.decode(from: "data", binding: "argument\(index)", mutable: mutable))")
            if mutable { lines.append("            let count\(index) = argument\(index).count") }
        }
        lines.append("            guard data.isAtEnd else { throw BinderError.failedTransaction }")
        let arguments = method.parameters.indices.map { index in
            (method.inoutParameters.contains(index) ? "&" : "") + "argument\(index)"
        }.joined(separator: ", ")
        let call = "try await self.\(escaped(method.name))(\(arguments))"
        lines.append("            " + (method.result == nil ? call : "let result = " + call))
        if !method.isOneway {
            for index in method.inoutParameters {
                lines.append("            guard argument\(index).count == count\(index) else { throw BinderError.failedTransaction }")
            }
            lines.append("            reply.writeNoException()")
            if let result = method.result {
                lines.append("            \(result.write("result", to: "reply"))")
            }
            for index in method.inoutParameters {
                lines.append("            \(method.parameters[index].write("argument\(index)", to: "reply"))")
            }
        }
        lines.append("            return true")
        return lines
    }

    private func makeMethod(_ method: AIDLMethod, interfaceIsOneway: Bool) throws -> Method {
        let context = "method '\(method.name)'"
        _ = try identifier(method.name)
        // The parser preserves annotations before the return type on the method.
        let returnAnnotations = method.annotations + method.returnType.annotations
        guard method.annotations.isEmpty || isNullableAnnotation(returnAnnotations) else {
            throw failure("Swift generation does not support annotations on \(context)")
        }
        // AOSP reserves the top 100 method IDs for compiler metadata.
        guard (1...16_777_115).contains(method.computedTransactionCode) else {
            throw failure("transaction ID out of range for \(context)")
        }

        let result: WireType?
        if method.returnType.name == "void", isPlain(method.returnType), method.annotations.isEmpty {
            result = nil
        } else {
            result = try wireType(method.returnType, leadingAnnotations: method.annotations, context: context)
        }
        let isOneway = interfaceIsOneway || method.isOneway
        if isOneway, result != nil {
            throw failure("oneway \(context) must return void")
        }
        var inoutParameters: [Int] = []
        let parameters = try method.parameters.enumerated().map { index, parameter in
            if parameter.direction != .in {
                guard parameter.direction == .inoutDirection, !isOneway,
                      parameter.type.arrayDimensions == 1, parameter.type.typeArguments.isEmpty,
                      parameter.type.annotations.isEmpty else {
                    throw failure("unsupported parameter direction for '\(parameter.name)' in \(context)")
                }
                inoutParameters.append(index)
            }
            return try wireType(parameter.type, context: context)
        }
        return Method(
            name: method.name, code: method.computedTransactionCode, parameters: parameters,
            result: result, isOneway: isOneway, stubValue: nil, inoutParameters: inoutParameters
        )
    }

    private func wireType(_ type: AIDLType, leadingAnnotations: [AIDLAnnotation] = [], context: String) throws -> WireType {
        let annotations = leadingAnnotations + type.annotations
        let nullable = isNullableAnnotation(annotations)
        if let reference = referenceType(type) {
            if annotations.isEmpty || nullable { return .reference(reference, nullable: nullable) }
        }
        if annotations.isEmpty || nullable,
           let collection = try collectionWireType(
               type, in: file, owner: file.declarations[0].name, nullable: nullable, context: context
           ) {
            return collection
        }
        if type.arrayDimensions == 0, type.typeArguments.isEmpty, annotations.isEmpty || nullable {
            if annotations.isEmpty, let scalar = Scalar(rawValue: type.name) { return .scalar(scalar) }
            let resolved = try resolver.resolve(type, in: file, scope: [file.declarations[0].name])
            if case let .declaration(name) = resolved.target, let symbol = resolver.symbols[name] {
                let declaration = symbol.declaration
                if case let .parcelable(parcelable) = declaration, parcelable.isOpaqueForwardDecl {
                    let swiftName = try manualParcelableName(name, context: context)
                    return .manualParcelable(
                        swiftName, qualifiedName: name, codec: file.declarations[0].name + "ManualParcelableCodec", nullable: nullable
                    )
                }
                let swiftName = try swiftDeclarationName(declaration.name, qualifiedName: name, context: context)
                if try validateTypedObject(symbol) {
                    return .parcelable(swiftName, qualifiedName: name, nullable: nullable)
                }
                if case let .enumeration(enumeration) = declaration, !nullable {
                    let backing = try enumBacking(enumeration)
                    return .enumeration(swiftName, qualifiedName: name, backing: backing)
                }
            }
        }
        throw failure("unsupported Swift wire type '\(type.name)' in \(context)")
    }

    private func collectionWireType(
        _ type: AIDLType, in file: AIDLFile, owner: String, nullable: Bool,
        context: String, ancestors: Set<String>? = nil
    ) throws -> WireType? {
        guard let elementName = collectionElementName(type) else { return nil }
        let codec = owner + "ArrayCodec"
        if elementName == "String" {
            return .stringCollection(codec: codec, nullable: nullable)
        }
        if type.arrayDimensions == 1, let scalar = Scalar(rawValue: elementName), scalar != .byte {
            return .scalarArray(scalar, codec: codec, nullable: nullable)
        }
        guard let name = try? resolver.resolveName(elementName, in: file, scope: [owner]),
              let symbol = resolver.symbols[name] else { return nil }
        if ancestors == nil, case let .parcelable(parcelable) = symbol.declaration, parcelable.isOpaqueForwardDecl {
            let swiftName = try manualParcelableName(name, context: context)
            return .parcelableCollection(
                swiftName, qualifiedName: name, codec: codec, nullable: nullable, manualCodec: owner + "ManualParcelableCodec"
            )
        }

        let backing: Scalar?
        if case let .enumeration(enumeration) = symbol.declaration, type.arrayDimensions == 1 {
            backing = try enumBacking(enumeration)
        } else {
            guard try validateTypedObject(symbol, ancestors: ancestors ?? []) else { return nil }
            backing = nil
        }

        let swiftName = if ancestors == nil {
            try swiftDeclarationName(symbol.declaration.name, qualifiedName: name, context: context)
        } else {
            try inlineDeclarationName(symbol, owner: owner, context: context)
        }
        if let backing {
            return .enumArray(swiftName, qualifiedName: name, backing: backing, codec: codec, nullable: nullable)
        }
        return .parcelableCollection(swiftName, qualifiedName: name, codec: codec, nullable: nullable)
    }

    private func manualParcelableName(_ qualifiedName: String, context: String) throws -> String {
        guard manualParcelables.contains(qualifiedName) else {
            throw failure("register opaque parcelable '\(qualifiedName)' with a manual BinderParcelable implementation")
        }
        let shortName = qualifiedName.split(separator: ".").last.map(String.init) ?? qualifiedName
        return try swiftDeclarationName(shortName, qualifiedName: qualifiedName, context: context)
    }

    private func collectionElementName(_ type: AIDLType) -> String? {
        if type.arrayDimensions == 1, type.typeArguments.isEmpty { return type.name }
        if type.name == "List", type.arrayDimensions == 0, type.typeArguments.count == 1,
           let element = type.typeArguments.first, isPlain(element) { return element.name }
        return nil
    }

    private func swiftDeclarationName(_ value: String, qualifiedName: String, context: String) throws -> String {
        let name = try identifier(value)
        let owner = file.declarations[0].name
        guard ![owner, owner + "Proxy", owner + "Stub", owner + "TransactionCode",
                owner + "ArrayCodec", owner + "ManualParcelableCodec"].contains(name) else {
            throw failure("Swift name collision for '\(qualifiedName)' in \(context)")
        }
        return name
    }

    private func validateTypedObject(_ symbol: AIDLSymbol, ancestors: Set<String> = []) throws -> Bool {
        switch symbol.declaration {
        case let .parcelable(parcelable):
            _ = try parcelableFields(parcelable, declaredIn: symbol.sourceFile, ancestors: ancestors)
        case let .union(union):
            _ = try unionFields(union, declaredIn: symbol.sourceFile, ancestors: ancestors)
        default:
            return false
        }
        return true
    }

    private func enumBacking(_ enumeration: AIDLEnum) throws -> Scalar {
        guard enumeration.annotations.allSatisfy({ $0.name == "Backing" }) else {
            throw failure("unsupported annotations on enum '\(enumeration.name)'")
        }
        switch try enumeration.integerBacking() {
        case .byte: return .byte
        case .int: return .int
        case .long: return .long
        }
    }

    private func generateEnum(_ enumeration: AIDLEnum) throws -> [String] {
        let name = escaped(try identifier(enumeration.name))
        let qualifiedName = (file.packageName + [enumeration.name]).joined(separator: ".")
        let backing = try enumBacking(enumeration)
        var lines = [
            "public struct \(name): RawRepresentable, Hashable, Sendable {",
            "    public let rawValue: \(backing.swiftType)",
            "",
            "    public init(rawValue: \(backing.swiftType)) {",
            "        self.rawValue = rawValue",
            "    }",
        ]
        if !enumeration.cases.isEmpty { lines.append("") }
        for member in enumeration.cases {
            let caseName = try identifier(member.name)
            guard caseName != "rawValue", let value = integerConstants[qualifiedName + "." + caseName] else {
                throw failure("cannot emit enum member '\(qualifiedName).\(caseName)'")
            }
            lines.append("    public static let \(escaped(caseName)) = Self(rawValue: \(value))")
        }
        lines.append("}")
        return lines
    }

    private func referenceType(_ type: AIDLType) -> Reference? {
        guard type.typeArguments.isEmpty else { return nil }
        switch (type.name, type.arrayDimensions) {
        case ("String", 0): return .string
        case ("byte", 1): return .bytes
        default: return nil
        }
    }

    private func isNullableAnnotation(_ annotations: [AIDLAnnotation]) -> Bool {
        annotations.count == 1 && annotations[0].name == "nullable" && annotations[0].arguments.isEmpty
    }

    private func parcelableFields(
        _ parcelable: AIDLParcelable, declaredIn file: AIDLFile, ancestors: Set<String> = []
    ) throws -> [(name: String, field: ParcelableField, initialValue: String)] {
        let name = parcelable.name
        guard !parcelable.isOpaqueForwardDecl, parcelable.annotations.isEmpty,
              parcelable.typeParameters.isEmpty, parcelable.constants.isEmpty,
              parcelable.nestedDeclarations.isEmpty else {
            throw failure("Swift generation requires a plain structured parcelable for '\(name)'")
        }
        let ancestry = try fieldAncestry(for: name, in: file, ancestors: ancestors)
        let fields = try fields(parcelable.fields, in: name) { field, context in
            let wire = try inlineField(field.type, in: file, owner: name, context: context, ancestors: ancestry)
            let initialValue = try field.defaultValue.map { tokens in
                try parcelableDefault(tokens, for: wire, in: file, owner: name, fieldName: field.name, context: context)
            } ?? wire.initialValue
            return (wire, initialValue)
        }
        try validateSwiftTypeNames(fields.map { $0.field.0.wireType })
        return fields.map { ($0.name, $0.field.0, $0.field.1) }
    }

    private func inlineField(
        _ type: AIDLType, in file: AIDLFile, owner: String, context: String, ancestors: Set<String>
    ) throws -> ParcelableField {
        let nullable = isNullableAnnotation(type.annotations)
        if let reference = referenceType(type), nullable || type.annotations.isEmpty {
            return .reference(reference, nullable: nullable)
        }
        if nullable || type.annotations.isEmpty,
           let collection = try collectionWireType(
               type, in: file, owner: owner, nullable: nullable, context: context, ancestors: ancestors
           ) {
            return .collection(collection, nullable: nullable)
        }
        if type.arrayDimensions == 0, type.typeArguments.isEmpty, type.annotations.isEmpty || nullable,
           let qualifiedName = try? resolver.resolveName(type.name, in: file, scope: [owner]),
           let symbol = resolver.symbols[qualifiedName] {
            switch symbol.declaration {
            case let .enumeration(enumeration) where !nullable:
                let name = try inlineDeclarationName(symbol, owner: owner, context: context)
                return .enumeration(name, qualifiedName: qualifiedName, backing: try enumBacking(enumeration))
            case let .parcelable(parcelable):
                _ = try parcelableFields(parcelable, declaredIn: symbol.sourceFile, ancestors: ancestors)
                let name = try inlineDeclarationName(symbol, owner: owner, context: context)
                return .parcelable(name, qualifiedName: qualifiedName, nullable: nullable)
            case let .union(union):
                _ = try unionFields(union, declaredIn: symbol.sourceFile, ancestors: ancestors)
                let name = try inlineDeclarationName(symbol, owner: owner, context: context)
                return .parcelable(name, qualifiedName: qualifiedName, nullable: nullable)
            default:
                break
            }
        }
        return .scalar(try scalar(type, context: context))
    }

    private func inlineDeclarationName(_ symbol: AIDLSymbol, owner: String, context: String) throws -> String {
        let name = try identifier(symbol.declaration.name)
        guard name != owner, name != owner + "ArrayCodec",
              symbol.qualifiedName == (symbol.sourceFile.packageName + [name]).joined(separator: ".") else {
            throw failure("unsupported Swift field type '\(symbol.qualifiedName)' in \(context)")
        }
        return name
    }

    private func parcelableDefault(
        _ tokens: [AIDLToken], for field: ParcelableField, in file: AIDLFile, owner: String,
        fieldName: String, context: String
    ) throws -> String {
        switch field {
        case let .scalar(type):
            if type == .boolean, tokens.count == 1,
               let literal = tokens.first?.text, literal == "true" || literal == "false" {
                return literal
            }
            if let backing = AIDLIntegerBacking(rawValue: type.rawValue) {
                let value = try AIDLConstantEvaluator().evaluateInteger(tokens) { _ in nil }.value
                guard AIDLInteger.fits(value, width: backing.width) else {
                    throw failure("default value \(value) does not fit in \(type.rawValue) for \(context)")
                }
                return String(value)
            }
        case .reference(.string, _):
            var evaluator = StringConstantEvaluator(definitions: [fieldName: tokens], interfaceDescriptor: "")
            return String(reflecting: try evaluator.evaluate(fieldName))
        case let .enumeration(name, qualifiedName, _):
            let parts = tokens.enumerated()
            guard tokens.count >= 3, tokens.count.isMultiple(of: 2) == false,
                  parts.allSatisfy({ $0.offset.isMultiple(of: 2) ? $0.element.kind == .identifier : $0.element.text == "." }),
                  let member = tokens.last?.text else {
                throw failure("expected a qualified enum member default for \(context)")
            }
            let enumName = tokens.dropLast(2).map(\.text).joined()
            guard (try? resolver.resolveName(enumName, in: file, scope: [owner])) == qualifiedName,
                  integerConstants[qualifiedName + "." + member] != nil else {
                throw failure("default for \(context) must reference a member of '\(qualifiedName)'")
            }
            return "\(escaped(name)).\(escaped(member))"
        default:
            break
        }
        throw failure("unsupported explicit default for \(context)")
    }

    private func unionFields(
        _ union: AIDLUnion, declaredIn file: AIDLFile, ancestors: Set<String> = []
    ) throws -> [(name: String, field: ParcelableField)] {
        guard union.annotations.isEmpty, union.constants.isEmpty, union.nestedDeclarations.isEmpty, !union.fields.isEmpty else {
            throw failure("Swift generation requires a plain union with at least one field for '\(union.name)'")
        }
        let ancestry = try fieldAncestry(for: union.name, in: file, ancestors: ancestors)
        let fields = try fields(union.fields, in: union.name) { field, context in
            guard field.defaultValue == nil else {
                throw failure("Swift generation does not support an explicit default for \(context)")
            }
            return try inlineField(field.type, in: file, owner: union.name, context: context, ancestors: ancestry)
        }
        try validateSwiftTypeNames(fields.map(\.field.wireType))
        return fields
    }

    private func fieldAncestry(for name: String, in file: AIDLFile, ancestors: Set<String>) throws -> Set<String> {
        let qualifiedName = (file.packageName + [name]).joined(separator: ".")
        var ancestry = ancestors
        guard ancestry.insert(qualifiedName).inserted else {
            throw failure("recursive Swift typed-object field involving '\(qualifiedName)'")
        }
        return ancestry
    }

    private func validateSwiftTypeNames(_ types: [WireType]) throws {
        var names: [String: String] = [:]
        for type in types {
            guard let (name, qualifiedName) = type.declarationIdentity else { continue }
            if let existing = names.updateValue(qualifiedName, forKey: name), existing != qualifiedName {
                throw failure("'\(existing)' and '\(qualifiedName)' share the Swift name '\(name)'")
            }
        }
    }

    private func fields<T>(
        _ fields: [AIDLField], in name: String, transform: (AIDLField, String) throws -> T
    ) throws -> [(name: String, field: T)] {
        var fieldNames = Set<String>()
        return try fields.map { field in
            let context = "field '\(name).\(field.name)'"
            _ = try identifier(field.name)
            guard fieldNames.insert(field.name).inserted,
                  !["write", "readTypedObject", "readNullableTypedObject", "writeTypedObject"].contains(field.name) else {
                throw failure("conflicting Swift name for \(context)")
            }
            return (escaped(field.name), try transform(field, context))
        }
    }

    private func generateUnion(_ union: AIDLUnion) throws -> [String] {
        let name = escaped(try identifier(union.name))
        let fields = try unionFields(union, declaredIn: file)
        guard let first = fields.first else { throw failure("union '\(union.name)' has no variants") }
        var lines = ["public enum \(name): BinderParcelable {"]
        lines += fields.map { "    case \($0.name)(\($0.field.wireType.swiftType))" }
        lines += [
            "",
            "    public init() {",
            "        self = .\(first.name)(\(first.field.initialValue))",
            "    }",
            "",
            "    public init(from reader: inout Parcel.Reader) throws {",
            "        switch try reader.readInt32() {",
        ]
        for (tag, field) in fields.enumerated() {
            let type = field.field.wireType
            lines.append("        case \(tag):")
            if type.requiresNonNullRead {
                lines.append("            \(type.decode(from: "reader", binding: "value"))")
                lines.append("            self = .\(field.name)(value)")
            } else {
                lines.append("            self = try .\(field.name)(\(type.read(from: "reader")))")
            }
        }
        lines += [
            "        default:",
            "            throw BinderError.failedTransaction",
            "        }",
            "    }",
            "",
            "    public func write(to parcel: inout Parcel) throws {",
            "        switch self {",
        ]
        for (tag, field) in fields.enumerated() {
            lines += [
                "        case let .\(field.name)(value):",
                "            parcel.append(Int32(\(tag)))",
                "            \(field.field.wireType.write("value", to: "parcel"))",
            ]
        }
        lines += ["        }", "    }"]
        return lines + Self.typedObjectMethods + ["}"]
            + arrayCodec(for: fields.map(\.field.wireType), owner: union.name)
    }

    private func generateParcelable(_ parcelable: AIDLParcelable) throws -> [String] {
        let name = escaped(try identifier(parcelable.name))
        let fields = try parcelableFields(parcelable, declaredIn: file)
        let size = fields.reduce(4) { $0 + $1.field.fixedWireSize }
        guard let wireSize = Int32(exactly: size) else {
            throw failure("parcelable '\(parcelable.name)' exceeds the size of a Binder parcel")
        }
        var lines = ["public struct \(name): BinderParcelable {"]
        lines += fields.map { "    public var \($0.name): \($0.field.wireType.swiftType)" }
        let parameters = fields.map { "\($0.name): \($0.field.wireType.swiftType) = \($0.initialValue)" }.joined(separator: ", ")
        lines += ["", "    public init(\(parameters)) {"]
        lines += fields.map { "        self.\($0.name) = \($0.name)" }
        lines += [
            "    }",
            "",
            "    public init(from reader: inout Parcel.Reader) throws {",
            "        let size = try reader.readInt32()",
            "        guard size >= 4, size.isMultiple(of: 4) else { throw ParcelError.invalidLength(size) }",
        ]
        if fields.isEmpty {
            lines.append("        _ = try reader.read(count: Int(size) - 4)")
        } else {
            lines.append("        var fields = Parcel(bytes: Array(try reader.read(count: Int(size) - 4))).reader()")
            for (name, field, initialValue) in fields {
                let type = field.wireType
                if type.requiresNonNullRead {
                    lines += [
                        "        if fields.isAtEnd {",
                        "            self.\(name) = \(initialValue)",
                        "        } else {",
                        "            \(type.decode(from: "fields", binding: "value"))",
                        "            self.\(name) = value",
                        "        }",
                    ]
                } else {
                    lines.append("        self.\(name) = fields.isAtEnd ? \(initialValue) : try \(type.read(from: "fields"))")
                }
            }
        }
        lines += [
            "    }",
            "",
            "    public func write(to parcel: inout Parcel) throws {",
        ]
        if fields.contains(where: { $0.field.requiresBufferedPayload }) {
            lines += [
                "        var payload = Parcel()",
            ]
            lines += fields.map { "        \($0.field.wireType.write("self." + $0.name, to: "payload"))" }
            lines += [
                "        guard payload.objectOffsets.isEmpty, payload.count.isMultiple(of: 4),",
                "              payload.count <= Int32.max - 4 else { throw BinderError.failedTransaction }",
                "        parcel.append(Int32(payload.count) + 4)",
                "        payload.bytes.withUnsafeBytes { bytes in",
                "            for offset in stride(from: 0, to: bytes.count, by: 4) {",
                "                parcel.append(bitPattern: bytes.loadUnaligned(fromByteOffset: offset, as: UInt32.self))",
                "            }",
                "        }",
                "    }",
            ]
            return lines + Self.typedObjectMethods + ["}"]
                + arrayCodec(for: fields.map(\.field.wireType), owner: parcelable.name)
        }
        let payloadSizes = fields.compactMap { $0.field.variablePayloadSize(of: "self." + $0.name) }
        if payloadSizes.isEmpty {
            lines.append("        parcel.append(Int32(\(wireSize)))")
        } else {
            lines.append("        var size: Int64 = \(wireSize)")
            lines += payloadSizes.map { "        size += \($0)" }
            lines += [
                "        guard let wireSize = Int32(exactly: size) else { throw BinderError.failedTransaction }",
                "        parcel.append(wireSize)",
            ]
        }
        lines += fields.map { "        \($0.field.wireType.write("self." + $0.name, to: "parcel"))" }
        lines.append("    }")
        return lines + Self.typedObjectMethods + ["}"]
    }

    private static let typedObjectMethods = [
        "",
        "    public static func readTypedObject(from reader: inout Parcel.Reader) throws -> Self {",
        "        guard let value = try readNullableTypedObject(from: &reader) else { throw BinderError.failedTransaction }",
        "        return value",
        "    }",
        "",
        "    public static func readNullableTypedObject(from reader: inout Parcel.Reader) throws -> Self? {",
        "        guard try reader.readInt32() != 0 else { return nil }",
        "        return try Self(from: &reader)",
        "    }",
        "",
        "    public func writeTypedObject(to parcel: inout Parcel) throws {",
        "        parcel.append(Int32(1))",
        "        try write(to: &parcel)",
        "    }",
    ]

    private func scalar(_ type: AIDLType, context: String) throws -> Scalar {
        guard isPlain(type), let scalar = Scalar(rawValue: type.name) else {
            throw failure("unsupported Swift wire type '\(type.name)' in \(context)")
        }
        return scalar
    }

    private func isPlain(_ type: AIDLType) -> Bool {
        type.arrayDimensions == 0 && type.typeArguments.isEmpty && type.annotations.isEmpty
    }

    private func identifier(_ value: String) throws -> String {
        let reserved: Set<String> = [
            "_", "self", "Self", "super", "init", "deinit", "asBinder", "descriptor",
            "onTransact", "transact", "interfaceDescriptor", "remote", "Parcel",
            "BinderProxy", "BinderStub", "BinderInterface", "IBinder", "TransactionFlags", "RemoteProxy", "RemoteEndpoint",
            "BinderTransactionError", "BinderError", "Int8", "Int32", "Int64", "UInt16", "UInt32",
            "UInt8", "UInt64", "Bool", "Float", "Double", "String", "Array", "BinderParcelable", "ParcelError",
            "RawRepresentable", "Hashable", "Sendable",
        ]
        guard !reserved.contains(value), value.utf8.allSatisfy({
            (65...90).contains($0) || (97...122).contains($0) || (48...57).contains($0) || $0 == 95
        }) else {
            throw failure("unsupported Swift identifier '\(value)'")
        }
        return value
    }

    private func failure(_ message: String) -> AIDLSwiftGenerationError {
        AIDLSwiftGenerationError(sourcePath: file.sourcePath, message: message)
    }

    private struct Method {
        let name: String
        let code: UInt32
        let parameters: [WireType]
        let result: WireType?
        let isOneway: Bool
        let stubValue: String?
        var inoutParameters: [Int] = []

        var signature: String {
            let inputs = parameters.enumerated().map { index, type in
                "_ argument\(index): \(inoutParameters.contains(index) ? "inout " : "")\(type.swiftType)"
            }
            let output = result.map { " -> \($0.swiftType)" } ?? ""
            return "func \(escaped(name))(\(inputs.joined(separator: ", "))) async throws\(output)"
        }
    }

    private enum WireType {
        case scalar(Scalar)
        case reference(Reference, nullable: Bool)
        case scalarArray(Scalar, codec: String, nullable: Bool)
        case stringCollection(codec: String, nullable: Bool)
        case parcelableCollection(String, qualifiedName: String, codec: String, nullable: Bool, manualCodec: String? = nil)
        case enumArray(String, qualifiedName: String, backing: Scalar, codec: String, nullable: Bool)
        case parcelable(String, qualifiedName: String, nullable: Bool)
        case manualParcelable(String, qualifiedName: String, codec: String, nullable: Bool)
        case enumeration(String, qualifiedName: String, backing: Scalar)

        var declarationIdentity: (String, String)? {
            switch self {
            case let .parcelable(name, qualifiedName, _), let .enumeration(name, qualifiedName, _),
                 let .parcelableCollection(name, qualifiedName, _, _, _), let .enumArray(name, qualifiedName, _, _, _),
                 let .manualParcelable(name, qualifiedName, _, _):
                (name, qualifiedName)
            default: nil
            }
        }

        var requiresNonNullRead: Bool {
            switch self {
            case .reference(_, nullable: false), .scalarArray(_, _, nullable: false),
                 .stringCollection(_, nullable: false), .parcelableCollection(_, _, _, nullable: false, _),
                 .enumArray(_, _, _, _, nullable: false): true
            default: false
            }
        }

        var usesArrayCodec: Bool {
            switch self {
            case .scalarArray, .stringCollection, .parcelableCollection: true
            case let .enumArray(_, _, backing, _, _): backing != .byte
            default: false
            }
        }

        var usesManualParcelableCodec: Bool {
            switch self {
            case .manualParcelable: true
            case let .parcelableCollection(_, _, _, _, manualCodec): manualCodec != nil
            default: false
            }
        }

        var swiftType: String {
            switch self {
            case let .scalar(type): type.swiftType
            case let .reference(type, nullable): type.swiftType + (nullable ? "?" : "")
            case let .scalarArray(type, _, nullable): "[\(type.swiftType)]" + (nullable ? "?" : "")
            case let .stringCollection(_, nullable): nullable ? "[String?]?" : "[String]"
            case let .parcelableCollection(name, _, _, nullable, _):
                "[" + escaped(name) + (nullable ? "?]?" : "]")
            case let .enumArray(name, _, _, _, nullable):
                "[" + escaped(name) + (nullable ? "]?" : "]")
            case let .parcelable(name, _, nullable), let .manualParcelable(name, _, _, nullable):
                escaped(name) + (nullable ? "?" : "")
            case let .enumeration(name, _, _): escaped(name)
            }
        }

        func read(from reader: String) -> String {
            switch self {
            case let .scalar(type): type.read(from: reader)
            case let .reference(type, _): "\(reader).\(type.readMethod)()"
            case let .scalarArray(type, codec, _):
                "\(codec).read(from: &\(reader), elementSize: \(type.wireSize), readElement: { try \(type.read(from: "$0")) })"
            case let .stringCollection(codec, nullable):
                "\(codec).read(from: &\(reader), elementSize: 4, readElement: \(nullable ? "{ try $0.readString() }" : codec + ".readRequiredString"))"
            case let .parcelableCollection(name, _, codec, nullable, manualCodec?):
                "\(codec).read(from: &\(reader), elementSize: 4, readElement: { try \(manualCodec).\(nullable ? "read" : "readRequired")(\(escaped(name)).self, from: &$0) })"
            case let .parcelableCollection(name, _, codec, nullable, nil):
                "\(codec).read(from: &\(reader), elementSize: 4, readElement: \(escaped(name)).\(nullable ? "readNullableTypedObject" : "readTypedObject"))"
            case let .enumArray(name, _, .byte, _, _):
                "\(reader).readBytes()?.map({ \(escaped(name))(rawValue: Int8(bitPattern: $0)) })"
            case let .enumArray(name, _, backing, codec, _):
                "\(codec).read(from: &\(reader), elementSize: \(backing.wireSize), readElement: { try \(escaped(name))(rawValue: \(backing.read(from: "$0"))) })"
            case let .parcelable(name, _, nullable):
                "\(escaped(name)).\(nullable ? "readNullableTypedObject" : "readTypedObject")(from: &\(reader))"
            case let .manualParcelable(name, _, codec, nullable):
                "\(codec).\(nullable ? "read" : "readRequired")(\(escaped(name)).self, from: &\(reader))"
            case let .enumeration(name, _, backing):
                "\(escaped(name))(rawValue: \(backing.read(from: reader)))"
            }
        }

        func decode(from reader: String, binding: String, mutable: Bool = false) -> String {
            let read = read(from: reader)
            let declaration = mutable ? "var" : "let"
            if requiresNonNullRead {
                return "guard \(declaration) \(binding) = try \(read) else { throw ParcelError.invalidLength(-1) }"
            }
            return "\(declaration) \(binding) = try \(read)"
        }

        func write(_ value: String, to parcel: String) -> String {
            switch self {
            case let .scalar(type): "\(parcel).\(type.append(value))"
            case let .reference(type, nullable: false): "\(parcel).\(type.append(value))"
            case let .reference(type, nullable: true):
                "if let value = \(value) { \(parcel).\(type.append("value")) } else { \(parcel).\(type.appendNullMethod)() }"
            case let .scalarArray(type, codec, _):
                "try \(codec).write(\(value), to: &\(parcel)) { $1.\(type.append("$0")) }"
            case let .stringCollection(codec, nullable: false):
                "try \(codec).write(\(value), to: &\(parcel)) { $1.append($0) }"
            case let .stringCollection(codec, nullable: true):
                "try \(codec).write(\(value), to: &\(parcel)) { if let value = $0 { $1.append(value) } else { $1.appendNullString() } }"
            case let .parcelableCollection(_, _, codec, _, manualCodec?):
                "try \(codec).write(\(value), to: &\(parcel)) { try \(manualCodec).write($0, to: &$1) }"
            case let .parcelableCollection(_, _, codec, nullable: false, nil):
                "try \(codec).write(\(value), to: &\(parcel)) { try $0.writeTypedObject(to: &$1) }"
            case let .parcelableCollection(_, _, codec, nullable: true, nil):
                "try \(codec).write(\(value), to: &\(parcel)) { if let value = $0 { try value.writeTypedObject(to: &$1) } else { $1.append(Int32(0)) } }"
            case .enumArray(_, _, .byte, _, nullable: false):
                "\(parcel).append(bytes: \(value).map { UInt8(bitPattern: $0.rawValue) })"
            case .enumArray(_, _, .byte, _, nullable: true):
                "if let value = \(value) { \(parcel).append(bytes: value.map { UInt8(bitPattern: $0.rawValue) }) } else { \(parcel).appendNullBytes() }"
            case let .enumArray(_, _, backing, codec, _):
                "try \(codec).write(\(value), to: &\(parcel)) { $1.\(backing.append("$0.rawValue")) }"
            case .parcelable(_, _, nullable: false): "try \(value).writeTypedObject(to: &\(parcel))"
            case .parcelable(_, _, nullable: true):
                "if let value = \(value) { try value.writeTypedObject(to: &\(parcel)) } else { \(parcel).append(Int32(0)) }"
            case let .manualParcelable(_, _, codec, _):
                "try \(codec).write(\(value), to: &\(parcel))"
            case let .enumeration(_, _, backing): "\(parcel).\(backing.append(value + ".rawValue"))"
            }
        }
    }

    private enum Reference {
        case string, bytes

        var swiftType: String { self == .string ? "String" : "[UInt8]" }
        var readMethod: String { self == .string ? "readString" : "readBytes" }
        var appendNullMethod: String { self == .string ? "appendNullString" : "appendNullBytes" }

        func append(_ value: String) -> String {
            self == .string ? "append(\(value))" : "append(bytes: \(value))"
        }
    }

    private enum ParcelableField {
        case scalar(Scalar)
        case reference(Reference, nullable: Bool)
        case enumeration(String, qualifiedName: String, backing: Scalar)
        case parcelable(String, qualifiedName: String, nullable: Bool)
        case collection(WireType, nullable: Bool)

        var requiresBufferedPayload: Bool {
            switch self {
            case .parcelable, .collection: true
            default: false
            }
        }

        var wireType: WireType {
            switch self {
            case let .scalar(type): .scalar(type)
            case let .reference(type, nullable): .reference(type, nullable: nullable)
            case let .enumeration(name, qualifiedName, backing):
                .enumeration(name, qualifiedName: qualifiedName, backing: backing)
            case let .parcelable(name, qualifiedName, nullable):
                .parcelable(name, qualifiedName: qualifiedName, nullable: nullable)
            case let .collection(type, _): type
            }
        }

        var initialValue: String {
            switch self {
            case let .scalar(type): type.zero
            case .reference(_, nullable: true): "nil"
            case .reference(.string, nullable: false): "\"\""
            case .reference(.bytes, nullable: false): "[]"
            case let .enumeration(name, _, _): "\(escaped(name))(rawValue: 0)"
            case let .parcelable(name, _, nullable): nullable ? "nil" : "\(escaped(name))()"
            case let .collection(_, nullable): nullable ? "nil" : "[]"
            }
        }

        // Reference fields always write a count, including for null values.
        var fixedWireSize: Int {
            switch self {
            case let .scalar(type): type.wireSize
            case .reference: 4
            case let .enumeration(_, _, backing): backing.wireSize
            case .parcelable, .collection: 0
            }
        }

        func variablePayloadSize(of value: String) -> String? {
            guard case let .reference(type, nullable) = self else { return nil }
            let member = type == .string ? "utf16.count" : "count"
            let count = nullable ? "value.\(member)" : "\(value).\(member)"
            let payload = type == .string ? "(Int64(\(count)) + 1) * 2" : "Int64(\(count))"
            let paddedSize = "((\(payload) + 3) & ~3)"
            return nullable ? "\(value).map { value in \(paddedSize) } ?? 0" : paddedSize
        }
    }

    private enum Scalar: String {
        case byte, int, long, boolean, char, float, double

        var zero: String { self == .boolean ? "false" : "0" }

        var wireSize: Int { self == .long || self == .double ? 8 : 4 }

        var swiftType: String {
            switch self {
            case .byte: "Int8"
            case .int: "Int32"
            case .long: "Int64"
            case .boolean: "Bool"
            case .char: "UInt16"
            case .float: "Float"
            case .double: "Double"
            }
        }

        func append(_ value: String) -> String {
            switch self {
            case .byte: "append(byte: \(value))"
            case .char: "append(character: \(value))"
            case .float: "append(Int32(bitPattern: \(value).bitPattern))"
            case .double: "append(Int64(bitPattern: \(value).bitPattern))"
            default: "append(\(value))"
            }
        }

        func read(from reader: String) -> String {
            switch self {
            case .byte: "\(reader).readByte()"
            case .int: "\(reader).readInt32()"
            case .long: "\(reader).readInt64()"
            case .boolean: "\(reader).readBool()"
            case .char: "\(reader).readCharacter()"
            case .float: "Float(bitPattern: UInt32(bitPattern: \(reader).readInt32()))"
            case .double: "Double(bitPattern: UInt64(bitPattern: \(reader).readInt64()))"
            }
        }
    }
}

private struct StringConstantEvaluator {
    let definitions: [String: [AIDLToken]]
    let interfaceDescriptor: String
    private var values: [String: String] = [:]
    private var active: Set<String> = []

    init(definitions: [String: [AIDLToken]], interfaceDescriptor: String) {
        self.definitions = definitions
        self.interfaceDescriptor = interfaceDescriptor
    }

    mutating func evaluate(_ name: String) throws -> String {
        if let value = values[name] { return value }
        guard let tokens = definitions[name], active.insert(name).inserted else {
            throw AIDLConstantEvaluationError(message: "unknown or cyclic String constant '\(name)'", location: definitions[name]?.first?.location)
        }
        defer { active.remove(name) }
        var index = 0
        let value = try concatenate(tokens, index: &index)
        guard index == tokens.count else {
            throw AIDLConstantEvaluationError(message: "expected '+' in String constant '\(name)'", location: tokens[index].location)
        }
        values[name] = value
        return value
    }

    private mutating func concatenate(_ tokens: [AIDLToken], index: inout Int) throws -> String {
        var value = try term(tokens, index: &index)
        while index < tokens.count, tokens[index].text == "+" {
            index += 1
            value += try term(tokens, index: &index)
        }
        return value
    }

    private mutating func term(_ tokens: [AIDLToken], index: inout Int) throws -> String {
        guard index < tokens.count else {
            throw AIDLConstantEvaluationError(message: "expected a String constant operand", location: tokens.last?.location)
        }
        let token = tokens[index]
        index += 1
        if token.kind == .stringLiteral {
            let contents = token.text.dropFirst().dropLast()
            guard contents.utf8.allSatisfy({ (0x20...0x7e).contains($0) && $0 != 0x5c }) else {
                throw AIDLConstantEvaluationError(message: "AIDL String literals require printable ASCII without backslashes", location: token.location)
            }
            return String(contents)
        }
        if token.text == "(" {
            let value = try concatenate(tokens, index: &index)
            guard index < tokens.count, tokens[index].text == ")" else {
                throw AIDLConstantEvaluationError(message: "expected ')' in String constant", location: token.location)
            }
            index += 1
            return value
        }
        guard token.kind == .identifier else {
            throw AIDLConstantEvaluationError(message: "expected a String literal or constant name", location: token.location)
        }
        var reference = token.text
        while index + 1 < tokens.count,
              tokens[index].text == ".", tokens[index + 1].kind == .identifier {
            reference += "." + tokens[index + 1].text
            index += 2
        }
        let interfaceName = interfaceDescriptor.split(separator: ".").last.map(String.init) ?? interfaceDescriptor
        for prefix in [interfaceDescriptor + ".", interfaceName + "."] where reference.hasPrefix(prefix) {
            reference.removeFirst(prefix.count)
            break
        }
        guard definitions[reference] != nil else {
            throw AIDLConstantEvaluationError(message: "unknown String constant '\(reference)' in '\(interfaceDescriptor)'", location: token.location)
        }
        return try evaluate(reference)
    }

}

private func escaped(_ name: String) -> String { "`\(name)`" }
