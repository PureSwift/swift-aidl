public struct AIDLSwiftGenerationError: Error, Sendable, CustomStringConvertible {
    public let sourcePath: String
    public let message: String

    public var description: String { "\(sourcePath): \(message)" }
}

/// Emits Swift bindings for the root declaration.
struct AIDLSwiftGenerator {
    let file: AIDLFile
    let resolver: AIDLTypeResolver
    let integerConstants: [String: Int64]
    let interfaceVersion: Int32?
    let interfaceHash: String?

    private static let header = ["// Generated by aidl-swift.", "import Binder", ""]

    func generate() throws -> String {
        guard file.declarations.count == 1, let declaration = file.declarations.first else {
            throw failure("Swift generation requires one declaration in the root file")
        }
        if interfaceVersion != nil || interfaceHash != nil {
            guard case .interface = declaration else {
                throw failure("version and hash options require an interface")
            }
        }
        let lines: [String]
        switch declaration {
        case let .interface(interface):
            lines = try generateInterface(interface)
        case let .parcelable(parcelable):
            lines = try generateParcelable(parcelable)
        case let .enumeration(enumeration):
            lines = try generateEnum(enumeration)
        case let .union(union):
            lines = try generateUnion(union)
        }
        return (Self.header + lines + [""]).joined(separator: "\n")
    }

    private func generateInterface(_ interface: AIDLInterface) throws -> [String] {
        guard interface.annotations.isEmpty, interface.nestedDeclarations.isEmpty else {
            throw failure("Swift generation does not support interface annotations or nested declarations")
        }
        let name = try identifier(interface.name)
        var methods = try interface.methods.map { try makeMethod($0, interfaceIsOneway: interface.isOneway) }
        guard Set(methods.map(\.name)).count == methods.count else {
            throw failure("Swift generation does not support overloaded methods")
        }
        guard Set(methods.map(\.code)).count == methods.count else {
            throw failure("duplicate transaction code")
        }
        let explicitCount = interface.methods.filter { $0.explicitTransactionId != nil }.count
        guard explicitCount == 0 || explicitCount == methods.count else {
            throw failure("transaction IDs must be specified for all methods or none")
        }
        for method in try metadataMethods() {
            guard !methods.contains(where: { $0.name == method.name }) else {
                throw failure("method '\(method.name)' conflicts with generated Stable AIDL metadata")
            }
            methods.append(method)
        }
        let constants = try generateInterfaceConstants(interface, methodNames: Set(methods.map(\.name)))
        var declarationNames: [String: String] = [:]
        for method in methods {
            let types = method.parameters + (method.result.map { [$0] } ?? [])
            for type in types {
                guard let (name, qualifiedName) = type.declarationIdentity else { continue }
                if let existing = declarationNames.updateValue(qualifiedName, forKey: name), existing != qualifiedName {
                    throw failure("'\(existing)' and '\(qualifiedName)' share the Swift name '\(name)'")
                }
            }
        }

        var lines = ["public protocol \(escaped(name)): BinderInterface {"]
        lines += methods.map { "    \($0.signature)" }
        lines += [
            "}",
            "",
            "public extension \(escaped(name)) {",
            "    static var descriptor: String { \(String(reflecting: interface.descriptor)) }",
        ]
        lines += constants
        lines += [
            "}",
            "",
            "public enum \(name)TransactionCode {",
        ]
        lines += methods.map { "    public static let \(escaped($0.name)): UInt32 = \($0.code)" }
        lines += [
            "}",
            "",
            "public struct \(name)Proxy: \(escaped(name)), BinderProxy {",
            "    public let remote: any IBinder",
            "",
            "    public init(remote: any IBinder) {",
            "        self.remote = remote",
            "    }",
            "",
            "    public init(remote: RemoteProxy) {",
            "        self.init(remote: RemoteEndpoint(proxy: remote))",
            "    }",
            "",
            "    private final class RemoteEndpoint: IBinder {",
            "        let proxy: RemoteProxy",
            "",
            "        init(proxy: RemoteProxy) {",
            "            self.proxy = proxy",
            "        }",
            "",
            "        func transact(code: UInt32, data: Parcel, flags: TransactionFlags) async throws -> Parcel {",
            "            try await proxy.transact(code: code, request: data, flags: flags)",
            "        }",
            "    }",
        ]
        for method in methods {
            lines += proxy(method, interfaceName: name)
        }
        lines += [
            "}",
            "",
            "open class \(name)Stub: BinderStub, \(escaped(name)), @unchecked Sendable {",
            "    public init() {",
            "        super.init(descriptor: Self.descriptor)",
            "    }",
            "",
            "    public final func asBinder() -> any IBinder { self }",
        ]
        for method in methods {
            let implementation = method.stubValue.map { "return " + $0 }
                ?? "throw BinderTransactionError.unknownTransaction(\(name)TransactionCode.\(escaped(method.name)))"
            lines += [
                "",
                "    open \(method.signature) {",
                "        \(implementation)",
                "    }",
            ]
        }
        lines += [
            "",
            "    public override func onTransact(",
            "        code: UInt32, data: inout Parcel.Reader, reply: inout Parcel, flags: TransactionFlags",
            "    ) async throws -> Bool {",
            "        switch code {",
        ]
        for method in methods {
            lines += dispatch(method, interfaceName: name)
        }
        lines += [
            "        default:",
            "            return try await super.onTransact(code: code, data: &data, reply: &reply, flags: flags)",
            "        }",
            "    }",
            "}",
        ]
        return lines
    }

    private func generateInterfaceConstants(_ interface: AIDLInterface, methodNames: Set<String>) throws -> [String] {
        var names = methodNames
        let declarations = try interface.constants.map { constant in
            let qualifiedName = interface.descriptor + "." + constant.name
            let name = try identifier(constant.name)
            guard names.insert(name).inserted else {
                throw failure("conflicting Swift name for interface constant '\(qualifiedName)'")
            }
            return constant
        }
        let strings = Dictionary(uniqueKeysWithValues: declarations
            .filter { $0.type.name == "String" && isPlain($0.type) }
            .map { ($0.name, $0.value) })
        var evaluator = StringConstantEvaluator(definitions: strings, interfaceDescriptor: interface.descriptor)
        return try declarations.map { constant in
            let qualifiedName = interface.descriptor + "." + constant.name
            let name = escaped(constant.name)
            if strings[constant.name] != nil {
                let value = try evaluator.evaluate(constant.name)
                return "    static var \(name): String { \(String(reflecting: value)) }"
            }
            if isPlain(constant.type), let type = Scalar(rawValue: constant.type.name),
               let value = integerConstants[qualifiedName] {
                return "    static var \(name): \(type.swiftType) { \(value) }"
            }
            throw failure("unsupported Swift type '\(constant.type.name)' for interface constant '\(qualifiedName)'")
        }
    }

    private func metadataMethods() throws -> [Method] {
        var methods: [Method] = []
        if let interfaceVersion {
            guard interfaceVersion > 0 else { throw failure("interface version must be positive") }
            methods.append(Method(
                name: "getInterfaceVersion", code: 0x00ff_ffff, parameters: [],
                result: .scalar(.int), isOneway: false, stubValue: String(interfaceVersion)
            ))
        }
        if let interfaceHash {
            guard !interfaceHash.isEmpty else { throw failure("interface hash must not be empty") }
            methods.append(Method(
                name: "getInterfaceHash", code: 0x00ff_fffe, parameters: [],
                result: .reference(.string, nullable: false), isOneway: false, stubValue: String(reflecting: interfaceHash)
            ))
        }
        return methods
    }

    private func proxy(_ method: Method, interfaceName: String) -> [String] {
        var lines = [
            "",
            "    public \(method.signature) {",
            "        var request = Parcel()",
            "        request.appendInterfaceToken(Self.descriptor)",
        ]
        for (index, type) in method.parameters.enumerated() {
            lines.append("        \(type.write("argument\(index)", to: "request"))")
        }
        let code = "\(interfaceName)TransactionCode.\(escaped(method.name))"
        if method.isOneway {
            lines.append("        _ = try await remote.transact(code: \(code), data: request, flags: .oneWay)")
        } else {
            lines += [
                "        let reply = try await remote.transact(code: \(code), data: request, flags: [])",
                "        var reader = reply.reader()",
                "        try reader.readException()",
            ]
            if let result = method.result {
                if result.requiresNonNullRead {
                    lines.append("        \(result.decode(from: "reader", binding: "result"))")
                    lines.append("        return result")
                } else {
                    lines.append("        return try \(result.read(from: "reader"))")
                }
            }
        }
        lines.append("    }")
        return lines
    }

    private func dispatch(_ method: Method, interfaceName: String) -> [String] {
        var lines = [
            "        case \(interfaceName)TransactionCode.\(escaped(method.name)):",
            "            try data.enforceInterface(Self.descriptor)",
        ]
        for (index, type) in method.parameters.enumerated() {
            lines.append("            \(type.decode(from: "data", binding: "argument\(index)"))")
        }
        lines.append("            guard data.isAtEnd else { throw BinderError.failedTransaction }")
        let arguments = method.parameters.indices.map { "argument\($0)" }.joined(separator: ", ")
        let call = "try await self.\(escaped(method.name))(\(arguments))"
        lines.append("            " + (method.result == nil ? call : "let result = " + call))
        if !method.isOneway {
            lines.append("            reply.writeNoException()")
            if let result = method.result {
                lines.append("            \(result.write("result", to: "reply"))")
            }
        }
        lines.append("            return true")
        return lines
    }

    private func makeMethod(_ method: AIDLMethod, interfaceIsOneway: Bool) throws -> Method {
        let context = "method '\(method.name)'"
        _ = try identifier(method.name)
        // The parser preserves annotations before the return type on the method.
        let returnAnnotations = method.annotations + method.returnType.annotations
        guard method.annotations.isEmpty || isNullableAnnotation(returnAnnotations) else {
            throw failure("Swift generation does not support annotations on \(context)")
        }
        // AOSP reserves the top 100 method IDs for compiler metadata.
        guard (1...16_777_115).contains(method.computedTransactionCode) else {
            throw failure("transaction ID out of range for \(context)")
        }

        let result: WireType?
        if method.returnType.name == "void", isPlain(method.returnType), method.annotations.isEmpty {
            result = nil
        } else {
            result = try wireType(method.returnType, leadingAnnotations: method.annotations, context: context)
        }
        let isOneway = interfaceIsOneway || method.isOneway
        if isOneway, result != nil {
            throw failure("oneway \(context) must return void")
        }
        let parameters = try method.parameters.map { parameter in
            guard parameter.direction == .in else {
                throw failure("Swift generation requires input parameters in \(context)")
            }
            return try wireType(parameter.type, context: context)
        }
        return Method(
            name: method.name, code: method.computedTransactionCode, parameters: parameters,
            result: result, isOneway: isOneway, stubValue: nil
        )
    }

    private func wireType(_ type: AIDLType, leadingAnnotations: [AIDLAnnotation] = [], context: String) throws -> WireType {
        let annotations = leadingAnnotations + type.annotations
        let nullable = isNullableAnnotation(annotations)
        if let reference = referenceType(type) {
            if annotations.isEmpty || nullable { return .reference(reference, nullable: nullable) }
        }
        if type.arrayDimensions == 0, type.typeArguments.isEmpty, annotations.isEmpty || nullable {
            if annotations.isEmpty, let scalar = Scalar(rawValue: type.name) { return .scalar(scalar) }
            let resolved = try resolver.resolve(type, in: file, scope: [file.declarations[0].name])
            if case let .declaration(name) = resolved.target, let declaration = resolver.symbols[name]?.declaration {
                let swiftName = try identifier(declaration.name)
                let owner = file.declarations[0].name
                guard ![owner, owner + "Proxy", owner + "Stub", owner + "TransactionCode"].contains(swiftName) else {
                    throw failure("Swift name collision for '\(name)' in \(context)")
                }
                switch declaration {
                case let .parcelable(parcelable):
                    _ = try parcelableFields(parcelable)
                    return .parcelable(swiftName, qualifiedName: name, nullable: nullable)
                case let .union(union):
                    _ = try unionFields(union)
                    return .parcelable(swiftName, qualifiedName: name, nullable: nullable)
                case let .enumeration(enumeration) where !nullable:
                    let backing = try enumBacking(enumeration)
                    return .enumeration(swiftName, qualifiedName: name, backing: backing)
                default: break
                }
            }
        }
        throw failure("unsupported Swift wire type '\(type.name)' in \(context)")
    }

    private func enumBacking(_ enumeration: AIDLEnum) throws -> Scalar {
        guard enumeration.annotations.allSatisfy({ $0.name == "Backing" }) else {
            throw failure("unsupported annotations on enum '\(enumeration.name)'")
        }
        switch try enumeration.integerBacking() {
        case .byte: return .byte
        case .int: return .int
        case .long: return .long
        }
    }

    private func generateEnum(_ enumeration: AIDLEnum) throws -> [String] {
        let name = escaped(try identifier(enumeration.name))
        let qualifiedName = (file.packageName + [enumeration.name]).joined(separator: ".")
        let backing = try enumBacking(enumeration)
        var lines = [
            "public struct \(name): RawRepresentable, Hashable, Sendable {",
            "    public let rawValue: \(backing.swiftType)",
            "",
            "    public init(rawValue: \(backing.swiftType)) {",
            "        self.rawValue = rawValue",
            "    }",
        ]
        if !enumeration.cases.isEmpty { lines.append("") }
        for member in enumeration.cases {
            let caseName = try identifier(member.name)
            guard caseName != "rawValue", let value = integerConstants[qualifiedName + "." + caseName] else {
                throw failure("cannot emit enum member '\(qualifiedName).\(caseName)'")
            }
            lines.append("    public static let \(escaped(caseName)) = Self(rawValue: \(value))")
        }
        lines.append("}")
        return lines
    }

    private func referenceType(_ type: AIDLType) -> Reference? {
        guard type.typeArguments.isEmpty else { return nil }
        switch (type.name, type.arrayDimensions) {
        case ("String", 0): return .string
        case ("byte", 1): return .bytes
        default: return nil
        }
    }

    private func isNullableAnnotation(_ annotations: [AIDLAnnotation]) -> Bool {
        annotations.count == 1 && annotations[0].name == "nullable" && annotations[0].arguments.isEmpty
    }

    private func parcelableFields(_ parcelable: AIDLParcelable) throws -> [(name: String, type: Scalar)] {
        let name = parcelable.name
        guard !parcelable.isOpaqueForwardDecl, parcelable.annotations.isEmpty,
              parcelable.typeParameters.isEmpty, parcelable.constants.isEmpty,
              parcelable.nestedDeclarations.isEmpty else {
            throw failure("Swift generation requires a plain structured parcelable for '\(name)'")
        }
        return try scalarFields(parcelable.fields, in: name)
    }

    private func unionFields(_ union: AIDLUnion) throws -> [(name: String, type: Scalar)] {
        guard union.annotations.isEmpty, union.constants.isEmpty, union.nestedDeclarations.isEmpty, !union.fields.isEmpty else {
            throw failure("Swift generation requires a plain union with at least one field for '\(union.name)'")
        }
        return try scalarFields(union.fields, in: union.name)
    }

    private func scalarFields(_ fields: [AIDLField], in name: String) throws -> [(name: String, type: Scalar)] {
        var fieldNames = Set<String>()
        return try fields.map { field in
            let context = "field '\(name).\(field.name)'"
            _ = try identifier(field.name)
            guard fieldNames.insert(field.name).inserted,
                  !["write", "readTypedObject", "readNullableTypedObject", "writeTypedObject"].contains(field.name) else {
                throw failure("conflicting Swift name for \(context)")
            }
            guard field.defaultValue == nil else {
                throw failure("Swift generation does not support an explicit default for \(context)")
            }
            return (escaped(field.name), try scalar(field.type, context: context))
        }
    }

    private func generateUnion(_ union: AIDLUnion) throws -> [String] {
        let name = escaped(try identifier(union.name))
        let fields = try unionFields(union)
        var lines = ["public enum \(name): BinderParcelable {"]
        lines += fields.map { "    case \($0.name)(\($0.type.swiftType))" }
        lines += [
            "",
            "    public init(from reader: inout Parcel.Reader) throws {",
            "        switch try reader.readInt32() {",
        ]
        for (tag, field) in fields.enumerated() {
            lines += [
                "        case \(tag):",
                "            self = try .\(field.name)(\(field.type.read(from: "reader")))",
            ]
        }
        lines += [
            "        default:",
            "            throw BinderError.failedTransaction",
            "        }",
            "    }",
            "",
            "    public func write(to parcel: inout Parcel) throws {",
            "        switch self {",
        ]
        for (tag, field) in fields.enumerated() {
            lines += [
                "        case let .\(field.name)(value):",
                "            parcel.append(Int32(\(tag)))",
                "            parcel.\(field.type.append("value"))",
            ]
        }
        lines += ["        }", "    }"]
        return lines + Self.typedObjectMethods + ["}"]
    }

    private func generateParcelable(_ parcelable: AIDLParcelable) throws -> [String] {
        let name = escaped(try identifier(parcelable.name))
        let fields = try parcelableFields(parcelable)
        let size = fields.reduce(4) { $0 + $1.type.wireSize }
        guard let wireSize = Int32(exactly: size) else {
            throw failure("parcelable '\(parcelable.name)' exceeds the size of a Binder parcel")
        }
        var lines = ["public struct \(name): BinderParcelable {"]
        lines += fields.map { "    public var \($0.name): \($0.type.swiftType)" }
        let parameters = fields.map { "\($0.name): \($0.type.swiftType) = \($0.type.zero)" }.joined(separator: ", ")
        lines += ["", "    public init(\(parameters)) {"]
        lines += fields.map { "        self.\($0.name) = \($0.name)" }
        lines += [
            "    }",
            "",
            "    public init(from reader: inout Parcel.Reader) throws {",
            "        let size = try reader.readInt32()",
            "        guard size >= 4, size.isMultiple(of: 4) else { throw ParcelError.invalidLength(size) }",
        ]
        if fields.isEmpty {
            lines.append("        _ = try reader.read(count: Int(size) - 4)")
        } else {
            lines.append("        var fields = Parcel(bytes: Array(try reader.read(count: Int(size) - 4))).reader()")
            lines += fields.map { "        self.\($0.name) = fields.isAtEnd ? \($0.type.zero) : try \($0.type.read(from: "fields"))" }
        }
        lines += [
            "    }",
            "",
            "    public func write(to parcel: inout Parcel) throws {",
            "        parcel.append(Int32(\(wireSize)))",
        ]
        lines += fields.map { "        parcel.\($0.type.append("self." + $0.name))" }
        lines.append("    }")
        return lines + Self.typedObjectMethods + ["}"]
    }

    private static let typedObjectMethods = [
        "",
        "    public static func readTypedObject(from reader: inout Parcel.Reader) throws -> Self {",
        "        guard let value = try readNullableTypedObject(from: &reader) else { throw BinderError.failedTransaction }",
        "        return value",
        "    }",
        "",
        "    public static func readNullableTypedObject(from reader: inout Parcel.Reader) throws -> Self? {",
        "        guard try reader.readInt32() != 0 else { return nil }",
        "        return try Self(from: &reader)",
        "    }",
        "",
        "    public func writeTypedObject(to parcel: inout Parcel) throws {",
        "        parcel.append(Int32(1))",
        "        try write(to: &parcel)",
        "    }",
    ]

    private func scalar(_ type: AIDLType, context: String) throws -> Scalar {
        guard isPlain(type), let scalar = Scalar(rawValue: type.name) else {
            throw failure("unsupported Swift wire type '\(type.name)' in \(context)")
        }
        return scalar
    }

    private func isPlain(_ type: AIDLType) -> Bool {
        type.arrayDimensions == 0 && type.typeArguments.isEmpty && type.annotations.isEmpty
    }

    private func identifier(_ value: String) throws -> String {
        let reserved: Set<String> = [
            "_", "self", "Self", "super", "init", "deinit", "asBinder", "descriptor",
            "onTransact", "transact", "interfaceDescriptor", "remote", "Parcel",
            "BinderProxy", "BinderStub", "BinderInterface", "IBinder", "TransactionFlags", "RemoteProxy", "RemoteEndpoint",
            "BinderTransactionError", "BinderError", "Int8", "Int32", "Int64", "UInt16", "UInt32",
            "UInt8", "UInt64", "Bool", "Float", "Double", "String", "Array", "BinderParcelable", "ParcelError",
            "RawRepresentable", "Hashable", "Sendable",
        ]
        guard !reserved.contains(value), value.utf8.allSatisfy({
            (65...90).contains($0) || (97...122).contains($0) || (48...57).contains($0) || $0 == 95
        }) else {
            throw failure("unsupported Swift identifier '\(value)'")
        }
        return value
    }

    private func failure(_ message: String) -> AIDLSwiftGenerationError {
        AIDLSwiftGenerationError(sourcePath: file.sourcePath, message: message)
    }

    private struct Method {
        let name: String
        let code: UInt32
        let parameters: [WireType]
        let result: WireType?
        let isOneway: Bool
        let stubValue: String?

        var signature: String {
            let inputs = parameters.enumerated().map { "_ argument\($0.offset): \($0.element.swiftType)" }
            let output = result.map { " -> \($0.swiftType)" } ?? ""
            return "func \(escaped(name))(\(inputs.joined(separator: ", "))) async throws\(output)"
        }
    }

    private enum WireType {
        case scalar(Scalar)
        case reference(Reference, nullable: Bool)
        case parcelable(String, qualifiedName: String, nullable: Bool)
        case enumeration(String, qualifiedName: String, backing: Scalar)

        var declarationIdentity: (String, String)? {
            switch self {
            case let .parcelable(name, qualifiedName, _), let .enumeration(name, qualifiedName, _):
                (name, qualifiedName)
            default: nil
            }
        }

        var requiresNonNullRead: Bool {
            if case .reference(_, nullable: false) = self { return true }
            return false
        }

        var swiftType: String {
            switch self {
            case let .scalar(type): type.swiftType
            case let .reference(type, nullable): type.swiftType + (nullable ? "?" : "")
            case let .parcelable(name, _, nullable): escaped(name) + (nullable ? "?" : "")
            case let .enumeration(name, _, _): escaped(name)
            }
        }

        func read(from reader: String) -> String {
            switch self {
            case let .scalar(type): type.read(from: reader)
            case let .reference(type, _): "\(reader).\(type.readMethod)()"
            case let .parcelable(name, _, nullable):
                "\(escaped(name)).\(nullable ? "readNullableTypedObject" : "readTypedObject")(from: &\(reader))"
            case let .enumeration(name, _, backing):
                "\(escaped(name))(rawValue: \(backing.read(from: reader)))"
            }
        }

        func decode(from reader: String, binding: String) -> String {
            let read = read(from: reader)
            if requiresNonNullRead {
                return "guard let \(binding) = try \(read) else { throw ParcelError.invalidLength(-1) }"
            }
            return "let \(binding) = try \(read)"
        }

        func write(_ value: String, to parcel: String) -> String {
            switch self {
            case let .scalar(type): "\(parcel).\(type.append(value))"
            case let .reference(type, nullable: false): "\(parcel).\(type.append(value))"
            case let .reference(type, nullable: true):
                "if let value = \(value) { \(parcel).\(type.append("value")) } else { \(parcel).\(type.appendNullMethod)() }"
            case .parcelable(_, _, nullable: false): "try \(value).writeTypedObject(to: &\(parcel))"
            case .parcelable(_, _, nullable: true):
                "if let value = \(value) { try value.writeTypedObject(to: &\(parcel)) } else { \(parcel).append(Int32(0)) }"
            case let .enumeration(_, _, backing): "\(parcel).\(backing.append(value + ".rawValue"))"
            }
        }
    }

    private enum Reference {
        case string, bytes

        var swiftType: String { self == .string ? "String" : "[UInt8]" }
        var readMethod: String { self == .string ? "readString" : "readBytes" }
        var appendNullMethod: String { self == .string ? "appendNullString" : "appendNullBytes" }

        func append(_ value: String) -> String {
            self == .string ? "append(\(value))" : "append(bytes: \(value))"
        }
    }

    private enum Scalar: String {
        case byte, int, long, boolean, char, float, double

        var zero: String { self == .boolean ? "false" : "0" }

        var wireSize: Int { self == .long || self == .double ? 8 : 4 }

        var swiftType: String {
            switch self {
            case .byte: "Int8"
            case .int: "Int32"
            case .long: "Int64"
            case .boolean: "Bool"
            case .char: "UInt16"
            case .float: "Float"
            case .double: "Double"
            }
        }

        func append(_ value: String) -> String {
            switch self {
            case .byte: "append(byte: \(value))"
            case .char: "append(character: \(value))"
            case .float: "append(Int32(bitPattern: \(value).bitPattern))"
            case .double: "append(Int64(bitPattern: \(value).bitPattern))"
            default: "append(\(value))"
            }
        }

        func read(from reader: String) -> String {
            switch self {
            case .byte: "\(reader).readByte()"
            case .int: "\(reader).readInt32()"
            case .long: "\(reader).readInt64()"
            case .boolean: "\(reader).readBool()"
            case .char: "\(reader).readCharacter()"
            case .float: "Float(bitPattern: UInt32(bitPattern: \(reader).readInt32()))"
            case .double: "Double(bitPattern: UInt64(bitPattern: \(reader).readInt64()))"
            }
        }
    }
}

private struct StringConstantEvaluator {
    let definitions: [String: [AIDLToken]]
    let interfaceDescriptor: String
    private var values: [String: String] = [:]
    private var active: Set<String> = []

    init(definitions: [String: [AIDLToken]], interfaceDescriptor: String) {
        self.definitions = definitions
        self.interfaceDescriptor = interfaceDescriptor
    }

    mutating func evaluate(_ name: String) throws -> String {
        if let value = values[name] { return value }
        guard let tokens = definitions[name], active.insert(name).inserted else {
            throw AIDLConstantEvaluationError(message: "unknown or cyclic String constant '\(name)'", location: definitions[name]?.first?.location)
        }
        defer { active.remove(name) }
        var index = 0
        let value = try concatenate(tokens, index: &index)
        guard index == tokens.count else {
            throw AIDLConstantEvaluationError(message: "expected '+' in String constant '\(name)'", location: tokens[index].location)
        }
        values[name] = value
        return value
    }

    private mutating func concatenate(_ tokens: [AIDLToken], index: inout Int) throws -> String {
        var value = try term(tokens, index: &index)
        while index < tokens.count, tokens[index].text == "+" {
            index += 1
            value += try term(tokens, index: &index)
        }
        return value
    }

    private mutating func term(_ tokens: [AIDLToken], index: inout Int) throws -> String {
        guard index < tokens.count else {
            throw AIDLConstantEvaluationError(message: "expected a String constant operand", location: tokens.last?.location)
        }
        let token = tokens[index]
        index += 1
        if token.kind == .stringLiteral {
            let contents = token.text.dropFirst().dropLast()
            guard contents.utf8.allSatisfy({ (0x20...0x7e).contains($0) && $0 != 0x5c }) else {
                throw AIDLConstantEvaluationError(message: "AIDL String literals require printable ASCII without backslashes", location: token.location)
            }
            return String(contents)
        }
        if token.text == "(" {
            let value = try concatenate(tokens, index: &index)
            guard index < tokens.count, tokens[index].text == ")" else {
                throw AIDLConstantEvaluationError(message: "expected ')' in String constant", location: token.location)
            }
            index += 1
            return value
        }
        guard token.kind == .identifier else {
            throw AIDLConstantEvaluationError(message: "expected a String literal or constant name", location: token.location)
        }
        var reference = token.text
        while index + 1 < tokens.count,
              tokens[index].text == ".", tokens[index + 1].kind == .identifier {
            reference += "." + tokens[index + 1].text
            index += 2
        }
        let interfaceName = interfaceDescriptor.split(separator: ".").last.map(String.init) ?? interfaceDescriptor
        for prefix in [interfaceDescriptor + ".", interfaceName + "."] where reference.hasPrefix(prefix) {
            reference.removeFirst(prefix.count)
            break
        }
        guard definitions[reference] != nil else {
            throw AIDLConstantEvaluationError(message: "unknown String constant '\(reference)' in '\(interfaceDescriptor)'", location: token.location)
        }
        return try evaluate(reference)
    }

}

private func escaped(_ name: String) -> String { "`\(name)`" }
